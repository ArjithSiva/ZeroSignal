/**
 * CLI: `npm run seed` / `npm run seed:clean`  (the only way to seed or clean).
 *
 *   npm run seed                      seed using SEED_EMAIL_DOMAIN and SEED_USER_PASSWORD (or a random password)
 *   npm run seed -- --force-production  allow seeding when NODE_ENV=production
 *   npm run seed:clean                remove exactly the seeded documents
 *   npm run seed -- --status          show counts only
 *
 * The shared password is printed once in the terminal and written to a git-ignored
 * SEED_CREDENTIALS.local.md. It is never stored anywhere the app can show it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import { config } from '../config/env.js';
import { checkPasswordPolicy, generatePassword } from '../services/auth/passwords.js';
import { cleanSeed, runSeed, seedStatus } from './index.js';

const args = process.argv.slice(2);
const command = args.find((a) => !a.startsWith('--')) ?? 'seed';
const flag = (n) => args.includes(`--${n}`);
const opt = (n) => args.find((a) => a.startsWith(`--${n}=`))?.split('=').slice(1).join('=');

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const DOMAIN_RE = /^(?=.{4,100}$)([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/i;

const redactHost = (uri) => uri.replace(/\/\/[^@/]*@/, '//***@').replace(/\?.*$/, '');

async function main() {
  if (!config.mongoUriConfigured) {
    console.error('✖ MONGODB_URI is not set. Copy server/.env.example to server/.env and add your MongoDB connection string.');
    process.exit(1);
  }
  if (config.isProd && !flag('force-production')) {
    console.error('✖ Refusing to run against a production environment (NODE_ENV=production).\n  Seeding writes demo-showcase history. If you really mean it, re-run with --force-production.');
    process.exit(1);
  }

  await mongoose.connect(config.mongoUri, { serverSelectionTimeoutMS: 10_000 });
  console.log(`Connected to ${redactHost(config.mongoUri)} (database "${mongoose.connection.name}").`);

  if (command === 'clean') {
    console.log('Removed seeded data:', await cleanSeed());
  } else if (command === 'seed' && flag('status')) {
    /* fallthrough to status print below */
  } else if (command === 'seed') {
    const emailDomain = (opt('domain') ?? process.env.SEED_EMAIL_DOMAIN ?? '').trim().toLowerCase();
    if (!DOMAIN_RE.test(emailDomain)) {
      console.error('✖ Set SEED_EMAIL_DOMAIN (e.g. SEED_EMAIL_DOMAIN=responders.example.org) in server/.env, or pass --domain=<domain>.');
      process.exit(1);
    }
    let password = process.env.SEED_USER_PASSWORD?.trim();
    const generated = !password;
    if (generated) password = generatePassword();
    else {
      const problems = checkPasswordPolicy(password);
      if (problems.length) {
        console.error(`✖ SEED_USER_PASSWORD is too weak: ${problems.join(' ')}`);
        process.exit(1);
      }
    }

    const { inserted, users } = await runSeed({ emailDomain, password, argon2: config.auth.argon2 });
    console.log('Seeded:', inserted);

    const lines = [
      '# Local sign-in details (generated by `npm run seed`)',
      '',
      'This file is git-ignored. Delete it when you no longer need it. These credentials are never shown in the app.',
      '',
      '| Name | Role | Email |',
      '|---|---|---|',
      ...users.map((u) => `| ${u.name} | ${u.role} | ${u.email} |`),
      '',
      `Password for all of the above: \`${password}\`${generated ? ' (randomly generated)' : ' (from SEED_USER_PASSWORD)'}`,
      '',
    ];
    console.log(`\nSeeded accounts (shared password ${generated ? 'generated, shown once' : 'from SEED_USER_PASSWORD'}):`);
    for (const u of users.filter((x) => x.role !== 'receiver').concat(users.filter((x) => x.role === 'receiver').slice(0, 1))) console.log(`  ${u.role.padEnd(12)} ${u.email}`);
    console.log(`  … ${users.length} accounts in total`);
    if (generated) console.log(`\n  PASSWORD: ${password}\n  (printed once — it is also written to SEED_CREDENTIALS.local.md)`);
    if (!flag('no-credentials-file')) {
      const file = path.join(repoRoot, 'SEED_CREDENTIALS.local.md');
      fs.writeFileSync(file, lines.join('\n'), { mode: 0o600 });
      console.log(`\nCredentials written to ${path.relative(process.cwd(), file) || file} (git-ignored).`);
    }
  } else {
    console.error(`Unknown command "${command}". Use "seed" or "clean".`);
    process.exitCode = 1;
  }
  console.log('Status:', JSON.stringify((await seedStatus()).counts));
}

main()
  .catch((err) => {
    console.error('✖ Seed failed:', err.message);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
